/** Lookup for a vocabulary entry of a given lesson ("word@lesson" wins over "word"). */
export function mnemonicKey(lessonId: string, ko: string): string | null {
  const own = `${ko}@${lessonId}`;
  if (MNEMONICS[own]) return own;
  return MNEMONICS[ko] ? ko : null;
}

export const mnemonicFor = (lessonId: string, ko: string): Mnemonic | null => {
  const k = mnemonicKey(lessonId, ko);
  return k ? MNEMONICS[k] : null;
};
